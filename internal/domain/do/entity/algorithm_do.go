package entity

import (
	"time"

	"awesomeProject/internal/domain/enum"
)

type Algorithm struct {
	ID                  string        `json:"id"` // Primary key generated by the server.
	Name                string        `json:"name"`
	Code                string        `json:"code"` // Globally unique algorithm code (letters and digits only).
	Description         string        `json:"description"`
	Category            string        `json:"category"`
	Author              string        `json:"author"`
	Language            enum.Language `json:"language"` // Development language (see enum.Language).
	Scene               string        `json:"scene"`
	Port                int           `json:"port"` // Listen port assigned by the platform when the process starts.
	Stateful            bool          `json:"stateful"`
	UpdateUser          string        `json:"updateUser"`
	LatestVersion       string        `json:"latestVersion"`
	LatestVersionStatus string        `json:"latestVersionStatus"`
	CreatedAt           time.Time     `json:"createdAt"`
	UpdatedAt           time.Time     `json:"updatedAt"`
}

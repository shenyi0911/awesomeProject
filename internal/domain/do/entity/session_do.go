package entity

import (
	"errors"
	"time"
)

// Session represents an algorithm invocation session.
type Session struct {
	SessionID     string    // Unique session ID generated by the platform (prefix "sess_").
	AlgorithmCode string    // Algorithm code owning the session; sessions are only reused within the same algorithm.
	Status        string    // active or closed (see enum.StatusActive and enum.StatusClosed).
	RequestCount  int       // Total requests served by the session, including the initial mint.
	CreatedAt     time.Time // Creation time.
	ExpiresAt     time.Time // Expiry time, extended by the TTL on every reuse.
	LastActiveAt  time.Time // Last activity time.
}

// DefaultTTL is the idle lifetime of a session (30 minutes).
const DefaultTTL = 30 * time.Minute

// Session errors shared by the repository and callers so the HTTP layer can map them to proper status codes.
var (
	ErrNotFound     = errors.New("session not found")
	ErrExpired      = errors.New("session expired")
	ErrCodeMismatch = errors.New("session code mismatch")
	ErrInactive     = errors.New("session inactive")
	// ErrTooMany means the active session limit for an algorithm has been reached
	// (controlled by SessionService.maxPerCode, unlimited by default). It tells clients that
	// stateful algorithms must reuse a session ID instead of minting one per call.
	ErrTooMany = errors.New("too many sessions for algorithm")
)
